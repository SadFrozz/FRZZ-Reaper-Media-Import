#pragma once

#include "video_hdr_color_shader.h"

static const char hdr_d3d11_color_source[] =
    "#define V3 float3\n#define V4 float4\n#define BLEND lerp\n"
    "cbuffer Color : register(b0) {\n" FRZZ_HDR_COLOR_FIELDS "};\n"
    FRZZ_HDR_COLOR_SHADER
    "RWTexture3D<float4> lattice : register(u0);\n"
    "[numthreads(8,8,1)] void main(uint3 p : SV_DispatchThreadID) {\n"
    "    if (p.x<65 && p.y<65 && p.z<65) lattice[p]=float4(hdr_to_sdr(float3(p)/64.0),1.0);\n"
    "}\n";

static const char hdr_d3d11_output_source[] =
    "cbuffer Output : register(b0) {\n"
    "    float2 size; float2 origin; float2 shift; float2 chroma_size;\n"
    "    float4 bridge_r,bridge_g,bridge_b,bridge_bias;\n"
    "};\n"
    "SamplerState linear_sampler : register(s0);\n"
    "Texture3D<float4> lattice : register(t2);\n"
    "#if HDR_BRIDGED\n"
    "Texture2D<float4> source_rgb : register(t0);\n"
    "#else\n"
    "Texture2D<float> source_y : register(t0);\n"
    "Texture2D<float2> source_uv : register(t1);\n"
    "#endif\n"
    "#if HDR_PACKED\n"
    "RWBuffer<unorm float4> packed_frame : register(u0);\n"
    "groupshared float luma_tile[128];\n"
    "#else\n"
    "RWTexture2D<unorm float> output_frame : register(u0);\n"
    "#endif\n"
    "groupshared float2 chroma_tile[128];\n"
    "[numthreads(16,8,1)] void main(uint3 id : SV_DispatchThreadID,uint i : SV_GroupIndex) {\n"
    "    uint2 p=id.xy;\n"
    "    int2 pixel=min(int2(p),int2(size)-1);\n"
    "#if HDR_BRIDGED\n"
    "    float3 rgb=source_rgb.Load(int3(pixel+int2(origin),0)).rgb;\n"
    "    float3 signal=rgb.r*bridge_r.xyz+rgb.g*bridge_g.xyz+rgb.b*bridge_b.xyz+bridge_bias.xyz;\n"
    "#else\n"
    "    float2 uv=clamp((float2(pixel)+0.5-shift)*0.5,0.5,size*0.5-0.5)+origin*0.5;\n"
    "    float3 signal=float3(source_y.Load(int3(pixel+int2(origin),0)),\n"
    "                         source_uv.SampleLevel(linear_sampler,uv/chroma_size,0));\n"
    "#endif\n"
    "    float3 color=lattice.SampleLevel(linear_sampler,(saturate(signal)*64.0+0.5)/65.0,0).rgb;\n"
    "    chroma_tile[i]=color.yz;\n"
    "#if HDR_PACKED\n"
    "    luma_tile[i]=color.x;\n"
    "#endif\n"
    "    GroupMemoryBarrierWithGroupSync();\n"
    "    if (any(p>=uint2(size))) return;\n"
    "#if HDR_PACKED\n"
    "    if ((p.x&3)==0) {\n"
    "        uint stride=uint(size.x)/4;\n"
    "        packed_frame[p.y*stride+p.x/4]=saturate(float4(luma_tile[i],luma_tile[i+1],luma_tile[i+2],luma_tile[i+3]));\n"
    "        if ((p.y&1)==0) {\n"
    "            float2 a=0.5*(chroma_tile[i]+chroma_tile[i+16]);\n"
    "            float2 b=0.5*(chroma_tile[i+2]+chroma_tile[i+18]);\n"
    "            packed_frame[(uint(size.y)+p.y/2)*stride+p.x/4]=saturate(float4(a,b));\n"
    "        }\n"
    "    }\n"
    "#else\n"
    "    output_frame[p]=saturate(color.x);\n"
    "    if (all((p&1)==0)) {\n"
    "        uint row=uint(size.y)+p.y/2;\n"
    "        float2 uv=saturate(0.5*(chroma_tile[i]+chroma_tile[i+16]));\n"
    "        output_frame[uint2(p.x,row)]=uv.x;\n"
    "        output_frame[uint2(p.x+1,row)]=uv.y;\n"
    "    }\n"
    "#endif\n"
    "}\n";
